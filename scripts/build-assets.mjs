// Regenerates src/assets.js from assets/*.png and assets/fonts/*.woff2. Images
// and fonts are inlined as data URIs so exported SVG files stay self-contained.
import fs from 'node:fs';

const NAMES = ['rod', 'radial', 'deep', 'back-panel'];
const root = new URL('../', import.meta.url);
const entries = NAMES.map(name => {
  const png = fs.readFileSync(new URL(`assets/${name}.png`, root));
  const width = png.readUInt32BE(16), height = png.readUInt32BE(20);
  return `  '${name}': { width: ${width}, height: ${height}, href: 'data:image/png;base64,${png.toString('base64')}' },`;
});
// Barlow (SIL OFL 1.1, assets/fonts/OFL.txt), latin subset.
const FONT_WEIGHTS = [400, 600];
const faces = FONT_WEIGHTS.map(w => {
  const woff2 = fs.readFileSync(new URL(`assets/fonts/barlow-${w}.woff2`, root));
  return `@font-face{font-family:Barlow;font-weight:${w};src:url(data:font/woff2;base64,${woff2.toString('base64')}) format('woff2')}`;
});
fs.writeFileSync(new URL('src/assets.js', root),
  `// Generated by scripts/build-assets.mjs. Do not edit by hand.\nexport const ASSETS = {\n${entries.join('\n')}\n};\nexport const FONT_FACES = "${faces.join('')}";\n`);
