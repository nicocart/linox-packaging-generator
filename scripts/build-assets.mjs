// Regenerates src/assets.js from assets/*.png. Images are inlined as data URIs
// so exported SVG files stay self-contained (no external references).
import fs from 'node:fs';

const NAMES = ['rod', 'radial', 'deep', 'back-panel'];
const root = new URL('../', import.meta.url);
const entries = NAMES.map(name => {
  const png = fs.readFileSync(new URL(`assets/${name}.png`, root));
  const width = png.readUInt32BE(16), height = png.readUInt32BE(20);
  return `  '${name}': { width: ${width}, height: ${height}, href: 'data:image/png;base64,${png.toString('base64')}' },`;
});
fs.writeFileSync(new URL('src/assets.js', root),
  `// Generated by scripts/build-assets.mjs from assets/*.png. Do not edit by hand.\nexport const ASSETS = {\n${entries.join('\n')}\n};\n`);
